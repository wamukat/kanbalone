import fs from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "public/icons.svg"), "utf8");
const names = ["folder-up", "folder-tree", "ticket", "check", "archive", "trash-2"];
const entries = names.map((name) => {
  const match = source.match(new RegExp(`<symbol id="${name}" viewBox="([^"]+)">([\\s\\S]*?)<\\/symbol>`));
  if (!match) throw new Error(`Missing canonical icon: ${name}`);
  const markup = `<svg class="icon" aria-hidden="true" focusable="false" viewBox="${match[1]}">${match[2].trim()}</svg>`;
  return `  ${JSON.stringify(name)}: ${JSON.stringify(markup)},`;
});
const output = `// @ts-check
// Generated by scripts/generate-group-icons.mjs from icons.svg; do not edit.
// Icons from Lucide, MIT License: https://lucide.dev/license
import { icon } from "./icons.js";

/** @type {Record<string, string>} */
const groupIcons = {
${entries.join("\n")}
};

/** Inline only repeated Group row icons to avoid SVG use layout overhead.
 * @param {string} name
 */
export function groupRowIcon(name) {
  return Object.hasOwn(groupIcons, name) ? groupIcons[name] : icon(name);
}
`;
const target = path.join(root, "public/app-group-icons.js");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== output) {
    throw new Error("Group icons are stale; run node scripts/generate-group-icons.mjs");
  }
} else {
  fs.writeFileSync(target, output);
}
